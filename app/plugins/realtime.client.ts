/**
 * Реалтайм ініціалізується на рівні застосунку, а не в компоненті — PRD §10.5.
 *
 * Причина конкретна: канал, створений у компоненті екрана, знищується при
 * навігації, і телевізор мовчки перестає отримувати події після переходу
 * між станами гри.
 *
 * Тут же живе синхронізація серверного годинника: її треба зробити один раз
 * до першого рендеру таймера, інакше перший відлік буде з чужим зсувом.
 */
export default defineNuxtPlugin(async () => {
  const clock = useServerClock()
  await clock.sync()
})
